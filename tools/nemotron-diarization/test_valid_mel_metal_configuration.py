"""Metal builds must select pristine sources and all20embedded assembly units."""
import json
from pathlib import Path
import tempfile
import unittest

from build_valid_mel_metal_sdk import verify_configuration
from valid_mel_metal_audit import KINDS


class MetalConfigurationTests(unittest.TestCase):
    def fixture(self, root):
        root = root.resolve()
        source = root / 'source'
        build = source / 'build/metal-diar'
        build.mkdir(parents=True)
        flags = {'NEMO_SPEECH_GGML_PATCHED:BOOL': 'OFF', 'GGML_METAL:BOOL': 'ON',
                 'GGML_METAL_EMBED_LIBRARY:BOOL': 'ON', 'GGML_CUDA:BOOL': 'OFF',
                 'GGML_VULKAN:BOOL': 'OFF', 'GGML_BACKEND_DL:BOOL': 'OFF',
                 'NEMO_SPEECH_LLAMA_CPP_SOURCE_DIR:PATH': '',
                 'ggml_SOURCE_DIR:STATIC': str(source / 'llama.cpp/ggml')}
        cache = '\n'.join(key + '=' + value for key, value in flags.items()) + '\n'
        (build / 'CMakeCache.txt').write_text(cache)
        code = source / 'real.cpp'
        code.write_bytes(b'actual source')
        commands = [{'file': str(code), 'arguments': ['c++', '-c', str(code)]}]
        commands += [{'file': str(build / 'ggml/src/ggml-metal/autogenerated' / ('ggml-metal-embed-' + kind + '.s')),
                      'arguments': ['cc', '-c', kind]} for kind in KINDS]
        (build / 'compile_commands.json').write_text(json.dumps(commands))
        return source, build, cache, commands

    def test_correct_metal_configuration_rejects_changed_flags_and_foreign_source_override(self):
        with tempfile.TemporaryDirectory() as temporary:
            source, build, cache, _ = self.fixture(Path(temporary))
            self.assertEqual(verify_configuration(source, build)['generated_shader_assembly_count'], 20)
            for before, after in [('GGML_METAL_EMBED_LIBRARY:BOOL=ON', 'GGML_METAL_EMBED_LIBRARY:BOOL=OFF'),
                                  ('NEMO_SPEECH_GGML_PATCHED:BOOL=OFF', 'NEMO_SPEECH_GGML_PATCHED:BOOL=ON'),
                                  ('NEMO_SPEECH_LLAMA_CPP_SOURCE_DIR:PATH=', 'NEMO_SPEECH_LLAMA_CPP_SOURCE_DIR:PATH=/foreign')]:
                (build / 'CMakeCache.txt').write_text(cache.replace(before, after))
                with self.subTest(before=before), self.assertRaises(ValueError):
                    verify_configuration(source, build)

    def test_missing_assembly_cpu_patch_define_and_unbound_generated_source_fail(self):
        with tempfile.TemporaryDirectory() as temporary:
            source, build, _, commands = self.fixture(Path(temporary))
            changes = [commands[:-1], commands + [{'file': str(build / 'unexpected.cpp'), 'arguments': ['c++']}],
                       [{**commands[0], 'arguments': ['c++', '-DNEMO_SPEECH_GGML_PATCHED=1']}, *commands[1:]]]
            for changed in changes:
                (build / 'compile_commands.json').write_text(json.dumps(changed))
                with self.subTest(changed=changed[0]), self.assertRaises(ValueError):
                    verify_configuration(source, build)


if __name__ == '__main__':
    unittest.main()
