"""Construct fresh tagged macOS arm64 Metal SDK; state/version checks, no models."""
import argparse
import json
from pathlib import Path
import platform
import re
import shlex
import subprocess
import sys
import time

from artifacts import digest
from build_valid_mel_candidate import descriptor
from runtime_profiles import load_profile, profile_provenance, verify_source
from valid_mel_metal_audit import KINDS, audit_pristine_llama, audit_shaders, pristine_files


def verify_configuration(source, build):
    source, build = Path(source).resolve(), Path(build).resolve()
    cache = (build / 'CMakeCache.txt').read_text()
    expected = {'NEMO_SPEECH_GGML_PATCHED:BOOL': 'OFF', 'GGML_METAL:BOOL': 'ON',
                'GGML_METAL_EMBED_LIBRARY:BOOL': 'ON', 'GGML_CUDA:BOOL': 'OFF',
                'GGML_VULKAN:BOOL': 'OFF', 'GGML_BACKEND_DL:BOOL': 'OFF',
                'NEMO_SPEECH_LLAMA_CPP_SOURCE_DIR:PATH': '',
                'ggml_SOURCE_DIR:STATIC': str(source / 'llama.cpp/ggml')}
    for name, value in expected.items():
        if not re.search(r'^' + re.escape(name + '=' + value) + r'$', cache, re.MULTILINE):
            raise ValueError('Metal compiler configuration differs: ' + name)
    entries = json.loads((build / 'compile_commands.json').read_text())
    generated = build / 'ggml/src/ggml-metal/autogenerated'
    expected_assembly = {generated / ('ggml-metal-embed-' + kind + '.s') for kind in KINDS}
    observed_assembly = set()
    files = {}
    for entry in entries:
        path = Path(entry['file']).resolve()
        args = entry.get('arguments') or shlex.split(entry['command'])
        if any('NEMO_SPEECH_GGML_PATCHED' in argument for argument in args):
            raise ValueError('Metal build unexpectedly defines CPU GGML patch compatibility')
        if path in expected_assembly:
            observed_assembly.add(path)
        elif not path.is_relative_to(source) or path.is_relative_to(source / 'build') or not path.is_file():
            raise ValueError('unexpected Metal compiler source: ' + str(path))
        if '_deps/llama.cpp' in str(path) or any('_deps/llama.cpp' in argument for argument in args):
            raise ValueError('Metal build selected the CPU materialized compiler tree')
        files[str(path)] = {'generated_shader_assembly': path in expected_assembly,
                            'source': descriptor(path) if path.is_file() else None}
    if observed_assembly != expected_assembly:
        raise ValueError('Metal compile commands omit embedded shader assembly')
    return {'cache_bindings': expected, 'compile_entry_count': len(entries),
            'generated_shader_assembly_count': len(observed_assembly), 'compiler_sources': files}


def verify_completed_source(source, patch):
    if subprocess.check_output(['git', 'diff', '--binary', '--no-ext-diff', '--ignore-submodules=all'], cwd=source) != patch.read_bytes():
        raise ValueError('native source differs after Metal construction')
    if subprocess.check_output(['git', 'diff', '--cached', '--binary', '--no-ext-diff', '--ignore-submodules=all'], cwd=source):
        raise ValueError('staged native source changed during Metal construction')
    for extra in [[], ['--ignored']]:
        paths = subprocess.check_output(['git', 'ls-files', '--others', *extra, '--exclude-standard'], cwd=source, text=True).splitlines()
        if any(not path.startswith('build/metal-diar/') for path in paths):
            raise ValueError('extra root compiler inputs outside the recorded Metal build')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['source', 'prefix', 'output']:
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--jobs', type=int, default=4)
    args = parser.parse_args()
    if platform.system() != 'Darwin' or platform.machine() != 'arm64' or args.jobs < 1:
        parser.error('this construction requires macOS arm64 and positive jobs')
    source, prefix, output = args.source.resolve(), args.prefix.resolve(), args.output.resolve()
    roots = [source, prefix, output]
    if len(set(roots)) != 3 or any(a != b and a.is_relative_to(b) for a in roots for b in roots):
        parser.error('source, SDK and evidence roots must be disjoint')
    if output.exists() or prefix.exists() or (source / 'build').exists():
        parser.error('refusing existing construction evidence, SDK prefix or source build')
    lock_path, lock = load_profile()
    verify_source(source, lock)
    source_commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=Path(__file__).resolve().parents[2], text=True).strip()
    output.mkdir(parents=True)
    (output / 'runtime-profile.json').write_bytes(lock_path.read_bytes())
    patch = lock_path.parent / lock['runtime']['compatibility_patches'][0]['path']
    (output / 'source.patch').write_bytes(patch.read_bytes())
    cache_root = Path.home() / '.cache/gen2-nemotron3-n0'
    profile = output / 'offline.sb'
    profile.write_text('(version 1)\n(allow default)\n(deny network*)\n'
        + '(deny file-read* ' + ' '.join('(subpath ' + json.dumps(str(path)) + ')' for path in
          [cache_root / 'assets', cache_root / 'native-f32-conversion-v1', cache_root / 'tail-framing-v1', source / 'test_files']) + ')\n'
        + '(deny file-write* ' + ' '.join('(subpath ' + json.dumps(str(path)) + ')' for path in
          [Path('/opt/homebrew'), source / 'llama.cpp', cache_root / 'valid-mel-macos-runtime-inputs-v1',
           cache_root / 'sdk-valid-mel-tagged-cpu-v1']) + ')\n')
    environment = {'PATH': '/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin', 'LC_ALL': 'C',
                   'GIT_LFS_SKIP_SMUDGE': '1', 'PYTHONDONTWRITEBYTECODE': '1'}
    commands = []

    def run(name, args, cwd=source, overrides=None):
        argv = ['/usr/bin/sandbox-exec', '-f', str(profile), *map(str, args)]
        env = {**environment, **(overrides or {})}
        record = {'phase': name, 'argv': argv, 'cwd': str(cwd), 'environment': env}
        commands.append(record)
        (output / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        start = time.monotonic()
        try:
            with (output / (name + '.stdout.log')).open('xb') as stdout, (output / (name + '.stderr.log')).open('xb') as stderr:
                result = subprocess.run(argv, cwd=cwd, env=env, stdout=stdout, stderr=stderr)
            record['returncode'] = result.returncode
        except OSError as error:
            record['startup_error'] = str(error)
            raise
        finally:
            record['elapsed_seconds'] = time.monotonic() - start
            (output / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        print(json.dumps({'phase': name, 'returncode': result.returncode}), flush=True)
        result.check_returncode()

    inventory = audit_pristine_llama(source, output, lock['runtime']['llama_revision'], run)
    preset = 'metal-diar'
    definitions = {**lock['runtime']['cmake_definitions'], 'NEMO_SPEECH_GGML_PATCHED': 'OFF',
        'GGML_METAL': 'ON', 'GGML_METAL_EMBED_LIBRARY': 'ON', 'GGML_CUDA': 'OFF', 'GGML_VULKAN': 'OFF',
        'GGML_BACKEND_DL': 'OFF', 'NEMO_SPEECH_LLAMA_CPP_SOURCE_DIR': '',
        'NEMO_SPEECH_BUILD_TESTS': 'ON', 'BUILD_TESTING': 'ON', 'CMAKE_EXPORT_COMPILE_COMMANDS': 'ON',
        'CMAKE_INSTALL_PREFIX': str(prefix)}
    run('configure', ['/bin/bash', 'scripts/configure.sh', preset,
                      *['-D' + key + '=' + value for key, value in definitions.items()]])
    build = source / 'build' / preset
    configured = verify_configuration(source, build)
    (output / 'compiler-admission.json').write_text(json.dumps(configured, indent=2) + '\n')
    run('build', ['/opt/homebrew/bin/cmake', '--build', '--preset', preset, '--parallel', str(args.jobs)])
    run('install', ['/opt/homebrew/bin/cmake', '--install', str(build)])
    run('model-free-state-test', ['/opt/homebrew/bin/ctest', '--test-dir', str(build), '--output-on-failure', '-R', '^diar_state$'])
    state = (output / 'model-free-state-test.stdout.log').read_text()
    if not re.search(r'1/1 Test #\d+: diar_state\s+.*Passed', state) or '100% tests passed, 0 tests failed out of 1' not in state:
        raise ValueError('required model-free Metal state test did not execute and pass')
    if pristine_files(source / 'llama.cpp') != inventory:
        raise ValueError('pristine Metal compiler tree changed during construction')
    verify_completed_source(source, patch)
    compiled = verify_configuration(source, build)
    (output / 'compiler-completed.json').write_text(json.dumps(compiled, indent=2) + '\n')
    for name in ['CMakeCache.txt', 'compile_commands.json', 'build.ninja', 'CMakeFiles/rules.ninja']:
        target = output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((build / name).read_bytes())
    shader = audit_shaders(source, build, prefix / 'lib/libggml-metal.0.25.1.dylib', output)
    query = ('import ctypes,sys; library=ctypes.CDLL(sys.argv[1]); '
             'version=library.nemo_speech_asr_version; version.restype=ctypes.c_char_p; '
             'print(version().decode("utf-8"))')
    run('version-only', [sys.executable, '-c', query, str(prefix / 'lib/libnemo_speech_asr_c.dylib')])
    version = (output / 'version-only.stdout.log').read_text().strip()
    if version != lock['runtime']['reported_version']:
        raise ValueError('actual tagged Metal version differs')
    toolchain = {}
    for phase, argv in [('cmake', ['/opt/homebrew/bin/cmake', '--version']),
                         ('ninja', ['/opt/homebrew/bin/ninja', '--version']),
                         ('clang', ['/usr/bin/clang++', '--version']),
                         ('xcode-sdk', ['/usr/bin/xcrun', '--show-sdk-version']),
                         ('brew-packages', ['/opt/homebrew/bin/brew', 'list', '--versions', 'sentencepiece', 'abseil', 'protobuf'])]:
        overrides = {'HOME': str(Path.home()), 'HOMEBREW_NO_AUTO_UPDATE': '1'} if phase == 'brew-packages' else None
        run('metadata-' + phase, argv, overrides=overrides)
        toolchain[phase] = (output / ('metadata-' + phase + '.stdout.log')).read_text().strip()
    toolchain['packages'] = toolchain['brew-packages']
    libraries, aliases = {}, {}
    for path in sorted((prefix / 'lib').iterdir()):
        if path.is_file():
            aliases[path.name] = {**descriptor(path), 'symlink_target': str(path.readlink()) if path.is_symlink() else None}
            if not path.is_symlink():
                libraries[path.name] = {'sha256': digest(path), 'size': path.stat().st_size,
                    'dependencies': subprocess.check_output(['/usr/bin/otool', '-L', str(path)], text=True),
                    'exports': subprocess.check_output(['/usr/bin/nm', '-gU', str(path)], text=True)}
    archive = build / 'src/runtime/ggml/libnemo_speech_runtime_ggml.a'
    record = {**profile_provenance(lock_path, lock), 'source_commit': source_commit,
              'backend': 'metal', 'preset': preset, 'metal_shaders_embedded': True,
              'metal_embedded_shader_text_bundles_verified': shader['shader_text_bundles'],
              'pristine_llama_compiler_tree_verified': True, 'cpu_ggml_patches_applied': False,
              'platform': platform.platform(), 'machine': platform.machine(), 'commands': commands,
              'cmake_definitions': definitions, 'toolchain': toolchain, 'libraries': libraries,
              'installed_library_paths': aliases, 'runtime_archive': {'path': str(archive), **descriptor(archive)},
              'cmake_cache_sha256': digest(build / 'CMakeCache.txt'), 'model_free_state_test_completed': True,
              'version_function_only_executed': True, 'model_instantiated_or_inference_performed': False,
              'artifact_admitted_for_inference': False, 'production_qualified': False, 'release_qualified': False}
    (output / 'build.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps({'constructed': True, 'backend': 'metal', 'version': version,
                      'embedded_shader_text_bundles_verified': 20, 'neural_calls': 0}), flush=True)


if __name__ == '__main__':
    main()
